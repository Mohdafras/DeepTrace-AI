"""Reproducible, non-training evaluation of the existing backend model.

Run with backend/.venv/Scripts/python.exe -I -B backend/tools/evaluate.py --help.
Dataset layout: {Train,Validation,Test}/{Fake,Real}/images, or
{train,valid,test}/{Fake,Real}/images. Splits and labels are never inferred,
randomly reassigned, or created. Every image in ALL splits is SHA-256 hashed
before selection: O(total dataset bytes), including Train even for a tiny test
subset. Identical bytes anywhere are rejected (including cross-label conflicts).
This detects exact duplicates, not perceptual duplicates or shared identities.

Outputs go only to explicitly supplied, NEW destinations; input images, model,
and active threshold are never overwritten. Validation alternatives are advisory
and never update threshold.json. Known-image labels are explicitly supplied by
an operator, not generated by the classifier. No charts or training are run.
"""
from __future__ import annotations

import argparse
from collections import Counter
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
import csv
import hashlib
import importlib.metadata
import importlib.util
import json
import math
from pathlib import Path
import platform
import random
import sys
from typing import Callable, Sequence

BACKEND = Path(__file__).resolve().parents[1]
DEFAULT_MODEL = BACKEND / "model" / "deepfake_model.keras"
DEFAULT_THRESHOLD = BACKEND / "model" / "threshold.json"
PREPROCESSING = BACKEND / "app" / "services" / "preprocessing.py"
DECODING = BACKEND / "app" / "utils" / "image_utils.py"
IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp"}
LABELS = {"Fake": 0, "Real": 1}
SPLITS = {"train": "train", "validation": "validation", "valid": "validation", "test": "test"}


class EvaluationError(ValueError):
    """Invalid or unsafe evaluation inputs."""


@dataclass(frozen=True)
class Sample:
    path: str
    split: str
    label: int
    label_name: str
    sha256: str
    bytes: int


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def image_sample(path: Path, split: str, label_name: str) -> Sample:
    if path.is_symlink():
        raise EvaluationError(f"Symlink images are not accepted: {path}")
    path = path.resolve(strict=True)
    if not path.is_file() or path.suffix.lower() not in IMAGE_EXTENSIONS:
        raise EvaluationError(f"Expected a JPG/JPEG/PNG/WEBP image: {path}")
    return Sample(str(path), split, LABELS[label_name], label_name, sha256_file(path), path.stat().st_size)


def reject_duplicates(samples: Sequence[Sample]) -> None:
    hashes: dict[str, Sample] = {}
    paths: dict[str, Sample] = {}
    for sample in samples:
        previous = hashes.get(sample.sha256) or paths.get(str(Path(sample.path).resolve()).casefold())
        if previous is not None:
            reason = "contradictory labels" if previous.label != sample.label else (
                "split overlap" if previous.split != sample.split else "duplicate image")
            raise EvaluationError(f"{reason}: {previous.path} and {sample.path}; identical path or SHA-256")
        hashes[sample.sha256] = sample
        paths[str(Path(sample.path).resolve()).casefold()] = sample


def scan_dataset(root: Path) -> list[Sample]:
    root = root.resolve(strict=True)
    if not root.is_dir():
        raise EvaluationError(f"Dataset root is not a directory: {root}")
    split_dirs: dict[str, Path] = {}
    for path in sorted(root.iterdir()):
        if path.is_symlink():
            raise EvaluationError(f"Symlinks are not accepted in the dataset: {path}")
        if not path.is_dir():
            continue
        split = SPLITS.get(path.name.casefold())
        if split is None:
            raise EvaluationError(f"Unknown split directory {path}; expected Train/Validation/Test or train/valid/test")
        if split in split_dirs:
            raise EvaluationError(f"Ambiguous duplicate split name: {path}")
        split_dirs[split] = path
    if set(split_dirs) != {"train", "validation", "test"}:
        raise EvaluationError("Dataset must contain existing train, validation (or valid), and test directories")
    samples: list[Sample] = []
    for split in ("train", "validation", "test"):
        classes: dict[str, Path] = {}
        for path in sorted(split_dirs[split].iterdir()):
            if path.is_symlink():
                raise EvaluationError(f"Symlinks are not accepted in the dataset: {path}")
            if not path.is_dir():
                continue
            label_name = {"fake": "Fake", "real": "Real"}.get(path.name.casefold())
            if label_name is None or label_name in classes:
                raise EvaluationError(f"Unknown or ambiguous class directory: {path}; use Fake and Real")
            classes[label_name] = path
        if set(classes) != set(LABELS):
            raise EvaluationError(f"Both Fake and Real class directories are required in {split_dirs[split]}")
        for label_name in LABELS:
            count = 0
            for path in sorted(classes[label_name].rglob("*")):
                if path.is_symlink():
                    raise EvaluationError(f"Symlinks are not accepted in the dataset: {path}")
                if path.is_file():
                    samples.append(image_sample(path, split, label_name))
                    count += 1
            if not count:
                raise EvaluationError(f"Empty class directory: {classes[label_name]}")
    reject_duplicates(samples)
    return samples


def select_samples(samples: Sequence[Sample], split: str, per_class: int | None, seed: int) -> list[Sample]:
    selected = sorted((s for s in samples if s.split == split), key=lambda s: s.path)
    if not selected:
        raise EvaluationError(f"No images in requested split: {split}")
    if per_class is not None:
        if per_class <= 0:
            raise EvaluationError("Balanced subset size must be positive")
        rng = random.Random(seed)
        subset = []
        for label in (0, 1):
            candidates = [s for s in selected if s.label == label]
            if len(candidates) < per_class:
                raise EvaluationError(f"Requested {per_class} per class; split {split}, label {label} has {len(candidates)}")
            subset.extend(rng.sample(candidates, per_class))
        selected = sorted(subset, key=lambda s: s.path)
    return selected


def threshold_value(value: object) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value) or not 0 <= value <= 1:
        raise EvaluationError("Threshold must be a finite number between 0 and 1")
    return float(value)


def load_threshold(path: Path) -> float:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise EvaluationError("Threshold JSON must be an object containing 'threshold'")
    return threshold_value(payload.get("threshold"))


def ratio(numerator: float, denominator: float) -> float | None:
    return numerator / denominator if denominator else None


def wilson_interval(successes: int, total: int) -> list[float] | None:
    if not total:
        return None
    z = 1.959963984540054
    p = successes / total
    denominator = 1 + z * z / total
    center = (p + z * z / (2 * total)) / denominator
    half = z * math.sqrt(p * (1 - p) / total + z * z / (4 * total * total)) / denominator
    return [max(0.0, center - half), min(1.0, center + half)]


def roc_auc_real(labels: Sequence[int], probabilities: Sequence[float]) -> float | None:
    positives = sum(labels)
    negatives = len(labels) - positives
    if not positives or not negatives:
        return None
    ordered = sorted(zip(probabilities, labels))
    positive_rank_sum = 0.0
    index = 0
    while index < len(ordered):
        end = index + 1
        while end < len(ordered) and ordered[end][0] == ordered[index][0]:
            end += 1
        rank = (index + 1 + end) / 2
        positive_rank_sum += rank * sum(label for _, label in ordered[index:end])
        index = end
    return (positive_rank_sum - positives * (positives + 1) / 2) / (positives * negatives)


def metrics(labels: Sequence[int], probabilities: Sequence[float], threshold: float) -> dict:
    threshold = threshold_value(threshold)
    if not labels or len(labels) != len(probabilities):
        raise EvaluationError("Metrics require matching, nonempty labels and probabilities")
    if any(type(label) is not int or label not in (0, 1) for label in labels):
        raise EvaluationError("Labels must be integer Fake=0 or Real=1")
    scores = [threshold_value(score) for score in probabilities]
    predicted = [int(score >= threshold) for score in scores]
    matrix = [[sum(y == actual and p == prediction for y, p in zip(labels, predicted))
               for prediction in (0, 1)] for actual in (0, 1)]
    tp, fn = matrix[0]  # Positive class is FAKE, unlike the sigmoid's REAL label.
    fp, tn = matrix[1]
    recall_fake, recall_real = ratio(tp, tp + fn), ratio(tn, tn + fp)
    return {
        "samples": len(labels), "threshold_real": threshold,
        "decision_rule": "REAL iff p_real >= threshold; otherwise FAKE", "positive_class": "Fake",
        "confusion_matrix": {"labels": ["Fake", "Real"], "rows_actual_columns_predicted": matrix},
        "counts": {"true_positive_fake": tp, "false_negative_fake_as_real": fn,
                   "false_positive_real_as_fake": fp, "true_negative_real": tn},
        "accuracy": (tp + tn) / len(labels),
        "precision_fake": ratio(tp, tp + fp), "recall_fake": recall_fake, "f1_fake": ratio(2 * tp, 2 * tp + fp + fn),
        "precision_real": ratio(tn, tn + fn), "recall_real": recall_real, "f1_real": ratio(2 * tn, 2 * tn + fn + fp),
        "balanced_accuracy": None if recall_fake is None or recall_real is None else (recall_fake + recall_real) / 2,
        "false_positive_rate_real_as_fake": ratio(fp, fp + tn),
        "false_negative_rate_fake_as_real": ratio(fn, fn + tp),
        "false_positive_rate_wilson_95": wilson_interval(fp, fp + tn),
        "false_negative_rate_wilson_95": wilson_interval(fn, fn + tp),
        "roc_auc_real_positive": roc_auc_real(labels, scores),
        "brier_score_real": sum((score - label) ** 2 for score, label in zip(scores, labels)) / len(labels),
        "undefined_metrics": "null when the denominator is zero; scores are not assumed calibrated",
    }


def prediction_rows(samples: Sequence[Sample], probabilities: Sequence[float], threshold: float) -> list[dict]:
    metrics([s.label for s in samples], probabilities, threshold)  # Validate before emitting rows.
    rows = []
    for sample, probability in zip(samples, probabilities):
        predicted = int(probability >= threshold)
        error = "correct" if predicted == sample.label else ("false_positive_real_as_fake" if sample.label == 1 else "false_negative_fake_as_real")
        rows.append({**asdict(sample), "ground_truth": sample.label_name, "p_real": probability,
                     "p_fake": 1 - probability, "prediction": "Real" if predicted else "Fake",
                     "threshold_real": threshold, "error_type": error})
    return rows


def new_destination(path: Path, protected: Sequence[Path], directory: bool = True) -> Path:
    path = path.resolve()
    if path.exists():
        raise EvaluationError(f"Output already exists; refusing to overwrite: {path}")
    if not path.parent.is_dir():
        raise EvaluationError(f"Output parent must already exist: {path.parent}")
    for source in [BACKEND / "model", *protected]:
        source = source.resolve()
        if path == source or (source.is_dir() and path.is_relative_to(source)):
            raise EvaluationError(f"Output must be outside input data/model locations: {path}")
    if not directory and path.suffix.lower() != ".json":
        raise EvaluationError("Known-image manifest output must end in .json")
    return path


def write_json(path: Path, payload: dict) -> None:
    with path.open("x", encoding="utf-8") as handle:
        json.dump(payload, handle, indent=2, allow_nan=False)
        handle.write("\n")


def collect_known(real: Sequence[Path], fake: Sequence[Path], label_source: str, output: Path) -> dict:
    if not label_source.strip():
        raise EvaluationError("A nonempty label-source description is required")
    samples = [image_sample(path, "known", name) for name, paths in (("Real", real), ("Fake", fake)) for path in paths]
    if not samples:
        raise EvaluationError("Supply at least one --real or --fake image")
    reject_duplicates(samples)
    samples.sort(key=lambda s: s.path)
    output = new_destination(output, [Path(s.path) for s in samples], directory=False)
    payload = {"schema_version": 1, "kind": "known_images", "label_mapping": LABELS,
               "label_source": label_source, "label_status": "operator-supplied ground truth; not independently verified",
               "created_utc": datetime.now(timezone.utc).isoformat(), "samples": [asdict(s) for s in samples]}
    write_json(output, payload)
    return payload


def read_known(path: Path) -> tuple[list[Sample], dict]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict) or payload.get("schema_version") != 1 or payload.get("kind") != "known_images" or payload.get("label_mapping") != LABELS:
        raise EvaluationError("Not a supported known-images manifest with Fake=0, Real=1")
    if not isinstance(payload.get("label_source"), str) or not payload["label_source"].strip():
        raise EvaluationError("Known-image manifest must include label_source")
    entries = payload.get("samples")
    if not isinstance(entries, list) or not entries:
        raise EvaluationError("Known-image manifest must contain samples")
    samples = []
    for entry in entries:
        if not isinstance(entry, dict) or entry.get("label_name") not in LABELS or type(entry.get("label")) is not int or entry["label"] != LABELS[entry["label_name"]] or entry.get("split") != "known":
            raise EvaluationError("Invalid or contradictory known-image label/split")
        image_path = Path(entry.get("path", ""))
        if not image_path.is_absolute():
            raise EvaluationError("Known-image manifest paths must be absolute")
        sample = image_sample(image_path, "known", entry["label_name"])
        if sample.sha256 != entry.get("sha256") or sample.bytes != entry.get("bytes"):
            raise EvaluationError(f"Known image changed since collection: {image_path}")
        samples.append(sample)
    reject_duplicates(samples)
    return samples, payload


def import_file(path: Path):
    spec = importlib.util.spec_from_file_location("evaluation_" + path.stem, path)
    if spec is None or spec.loader is None:
        raise EvaluationError(f"Cannot import preprocessing module: {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def load_predictor(model_path: Path, seed: int) -> Callable[[Sequence[Sample], int], list[float]]:
    # Lazy imports: inventory/metrics/tests/help do not import TensorFlow or load a model.
    import numpy as np
    import tensorflow as tf
    tf.keras.utils.set_random_seed(seed)
    tf.config.experimental.enable_op_determinism()
    preprocess = import_file(PREPROCESSING).preprocess_image
    decode = import_file(DECODING).decode_image
    model = tf.keras.models.load_model(str(model_path), compile=False, safe_mode=True)
    if model.input_shape != (None, 224, 224, 3) or model.output_shape != (None, 1):
        raise EvaluationError(f"Model contract mismatch: input={model.input_shape}, output={model.output_shape}")
    if model.layers[-1].get_config().get("activation") != "sigmoid" or str(model.inputs[0].dtype) != "float32":
        raise EvaluationError("Expected float32 RGB input and a single sigmoid output")

    def predict(samples: Sequence[Sample], batch_size: int) -> list[float]:
        probabilities = []
        for start in range(0, len(samples), batch_size):
            batch = []
            for sample in samples[start:start + batch_size]:
                content = Path(sample.path).read_bytes()
                if hashlib.sha256(content).hexdigest() != sample.sha256:
                    raise EvaluationError(f"Image changed during evaluation: {sample.path}")
                with decode(content, Path(sample.path).name) as image:
                    array = preprocess(image)
                if array.shape != (1, 224, 224, 3) or array.dtype != np.float32 or not np.isfinite(array).all() or array.min() < 0 or array.max() > 255:
                    raise EvaluationError(f"Preprocessing contract mismatch: {sample.path}")
                batch.append(array)
            output = np.asarray(model(np.concatenate(batch, axis=0), training=False))
            if output.shape != (len(batch), 1):
                raise EvaluationError(f"Unexpected prediction shape: {output.shape}")
            probabilities.extend(float(value) for value in output[:, 0])
        return probabilities
    return predict


def package_versions() -> dict:
    versions = {}
    for name in ("tensorflow", "keras", "numpy", "pillow"):
        try:
            versions[name] = importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError:
            versions[name] = "not installed"
    return {"python": sys.version, "platform": platform.platform(), "packages": versions}


def run_evaluation(args: argparse.Namespace, predictor_factory=load_predictor) -> dict:
    if args.batch_size <= 0 or not 0 <= args.seed <= 2147483647:
        raise EvaluationError("Batch size must be positive and seed must be in [0, 2147483647]")
    known = getattr(args, "known_manifest", None)
    candidates = getattr(args, "thresholds", None)
    if known:
        if args.split is not None or candidates is not None:
            raise EvaluationError("Known manifests do not accept split selection or threshold alternatives")
        inventory, known_payload = read_known(known)
        split = "known"
        source = {"known_manifest": str(known.resolve()), "manifest_sha256": sha256_file(known),
                  "label_source": known_payload["label_source"], "label_status": "operator-supplied; not independently verified"}
        protected = [known, *[Path(s.path) for s in inventory]]
    else:
        if candidates is not None and args.split != "validation":
            raise EvaluationError("Threshold alternatives are allowed only on validation, never test")
        inventory = scan_dataset(args.dataset_root)
        split = args.split or "test"
        source = {"dataset_root": str(args.dataset_root.resolve()), "label_source": "explicit Fake/Real class directories"}
        protected = [args.dataset_root]
    selected = select_samples(inventory, split, args.balanced_per_class, args.seed)
    model_path, threshold_path = args.model.resolve(strict=True), args.threshold_file.resolve(strict=True)
    threshold = load_threshold(threshold_path)
    alternatives = sorted(set(threshold_value(t) for t in candidates)) if candidates is not None else None
    protected.extend([model_path.parent, threshold_path, PREPROCESSING, DECODING, Path(__file__)])
    output = new_destination(args.output_dir, protected)
    tracked = {"model": model_path, "threshold_file": threshold_path, "preprocessing": PREPROCESSING,
               "decoding": DECODING, "evaluation_script": Path(__file__).resolve()}
    fingerprints = {key: {"path": str(path), "sha256": sha256_file(path)} for key, path in tracked.items()}
    probabilities = predictor_factory(model_path, args.seed)(selected, args.batch_size)
    fixed_metrics = metrics([s.label for s in selected], probabilities, threshold)
    for key, path in tracked.items():
        if sha256_file(path) != fingerprints[key]["sha256"]:
            raise EvaluationError(f"Input artifact changed during evaluation: {path}")
    provenance = {"created_utc": datetime.now(timezone.utc).isoformat(), "environment": package_versions(),
                  "artifacts": fingerprints, "source": source, "seed": args.seed, "batch_size": args.batch_size,
                  "balanced_per_class": args.balanced_per_class, "split": split,
                  "label_mapping": LABELS, "fixed_saved_threshold": threshold,
                  "inference": "training=False; deterministic TensorFlow ops; current backend decode/preprocess",
                  "preprocessing_contract": "Pillow RGB, TF bilinear 224x224 antialias=False, float32 0..255; no EXIF/crop/external normalization",
                  "reproducibility_limit": "Exact scores may differ across runtime/hardware versions; provenance records the environment"}
    counts = dict(Counter(f"{s.split}/{s.label_name}" for s in inventory))
    manifest = {"schema_version": 1, "provenance": provenance, "inventory_counts": counts,
                "deduplication": "All supplied split images SHA-256 hashed; repeated paths/hashes rejected; no perceptual/identity deduplication",
                "inventory": [asdict(s) for s in inventory], "selected_paths": [s.path for s in selected]}
    report = {"schema_version": 1, "provenance": provenance, "metrics": fixed_metrics,
              "evaluation_scope": "Known-image smoke evaluation, not a held-out generalization estimate" if known else "Existing supplied split; no repartitioning or relabeling",
              "subset_warning": "Balanced subset changes class prevalence and precision; not representative of deployment prevalence" if args.balanced_per_class else None,
              "interval_warning": "Wilson intervals assume independent images; related identities/frames can invalidate that assumption"}
    # No destination is created until scanning, inference, and provenance checks succeed.
    output.mkdir(exist_ok=False)
    write_json(output / "manifest.json", manifest)
    write_json(output / "evaluation.json", report)
    rows = prediction_rows(selected, probabilities, threshold)
    with (output / "predictions.csv").open("x", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    if alternatives is not None:
        write_json(output / "validation_thresholds.json", {
            "schema_version": 1, "provenance": provenance, "split": "validation",
            "notice": "Exploratory validation-only alternatives. Active threshold and model are unchanged. Do not select thresholds using test outcomes.",
            "fixed_saved_threshold": threshold,
            "alternatives": [metrics([s.label for s in selected], probabilities, t) for t in alternatives]})
    return report


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    evaluate = commands.add_parser("evaluate", help="Evaluate test/validation or a collected known-image manifest at the saved threshold")
    inputs = evaluate.add_mutually_exclusive_group(required=True)
    inputs.add_argument("--dataset-root", type=Path)
    inputs.add_argument("--known-manifest", type=Path)
    evaluate.add_argument("--split", choices=("test", "validation"), default=None, help="Dataset split; default test. Not accepted with --known-manifest")
    validate = commands.add_parser("validation-thresholds", help="Compare advisory thresholds using validation ONLY; never update active configuration")
    validate.add_argument("--dataset-root", type=Path, required=True)
    validate.add_argument("--thresholds", type=float, nargs="+", required=True)
    validate.set_defaults(split="validation", known_manifest=None)
    for command in (evaluate, validate):
        command.add_argument("--model", type=Path, default=DEFAULT_MODEL)
        command.add_argument("--threshold-file", type=Path, default=DEFAULT_THRESHOLD)
        command.add_argument("--output-dir", type=Path, required=True, help="New directory outside dataset/model directories; parent must exist")
        command.add_argument("--balanced-per-class", type=int, default=None, help="Optional seeded sample count PER class; scans/hashes ALL splits first")
        command.add_argument("--seed", type=int, default=42)
        command.add_argument("--batch-size", type=int, default=8)
    collect = commands.add_parser("collect-known", help="Collect explicit operator labels and image hashes without copying images or running inference")
    collect.add_argument("--real", type=Path, action="append", default=[], help="Known real image; repeat for more images")
    collect.add_argument("--fake", type=Path, action="append", default=[], help="Known fake image; repeat for more images")
    collect.add_argument("--label-source", required=True, help="How the ground-truth labels were established; not model predictions")
    collect.add_argument("--output-manifest", type=Path, required=True, help="New .json path; parent must exist")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    sys.dont_write_bytecode = True
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        if args.command == "collect-known":
            payload = collect_known(args.real, args.fake, args.label_source, args.output_manifest)
            print(f"Collected {len(payload['samples'])} explicitly labeled image references: {args.output_manifest.resolve()}")
        else:
            report = run_evaluation(args)
            print(json.dumps({"output_dir": str(args.output_dir.resolve()), "split": report["provenance"]["split"],
                              "samples": report["metrics"]["samples"], "threshold": report["metrics"]["threshold_real"],
                              "accuracy": report["metrics"]["accuracy"]}, allow_nan=False))
        return 0
    except (EvaluationError, OSError, ValueError) as exc:
        print(f"Evaluation refused: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
